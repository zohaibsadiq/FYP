"""
Cloudinary upload helper.

Every image in this project - original garment photos, background-removed
cutouts, user body photos, generated try-on results - goes through this one
file. Nothing else in the codebase calls Cloudinary directly.

Why one file?
  * If we ever swap Cloudinary for S3, only this file changes.
  * Credentials are configured once, not in five places.
  * Folder naming stays consistent instead of drifting per feature.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import IO, Any

import cloudinary
import cloudinary.api
import cloudinary.uploader
from django.conf import settings

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Configure the SDK once, when Django imports this module
# ---------------------------------------------------------------------------
cloudinary.config(
    cloud_name=settings.CLOUDINARY["cloud_name"],
    api_key=settings.CLOUDINARY["api_key"],
    api_secret=settings.CLOUDINARY["api_secret"],
    secure=True,  # always return https:// URLs
)


class CloudinaryNotConfigured(RuntimeError):
    """Raised when the .env keys are missing, instead of a confusing SDK error."""


def is_configured() -> bool:
    return all(settings.CLOUDINARY.values())


def _require_config() -> None:
    if not is_configured():
        raise CloudinaryNotConfigured(
            "Cloudinary keys are missing. Add CLOUDINARY_CLOUD_NAME, "
            "CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET to backend/.env"
        )


# ---------------------------------------------------------------------------
# Folder names - one place, so we never typo a folder into existence
# ---------------------------------------------------------------------------
class Folder:
    """Subfolders inside the project's Cloudinary root folder."""

    GARMENT_ORIGINAL = "garments/original"   # exactly what the user uploaded
    GARMENT_CLEAN = "garments/clean"         # after rembg removed the background
    BODY_PHOTO = "users/body"                # full-body photo used by try-on
    TRY_ON_RESULT = "tryon/results"          # images generated by the try-on model
    INSPIRATION = "inspiration"              # "Steal the Look" uploads


@dataclass(frozen=True)
class UploadedImage:
    """
    What we get back after a successful upload.

    `public_id` is Cloudinary's internal name for the file. We store it in the
    database next to the URL, because deleting an image later needs the
    public_id, not the URL.
    """

    url: str
    public_id: str
    width: int
    height: int
    bytes: int
    format: str

    @property
    def size_kb(self) -> int:
        return round(self.bytes / 1024)


def folder_for(folder: str, user_id: int | None) -> str:
    """
    Build the full Cloudinary folder path, with the user's own subfolder.

    Giving every user their own subfolder does two jobs:
      1. the media library stays browsable instead of one flat pile
      2. it lets the API verify that an image a client refers to was really
         uploaded by that same user - see `owns_public_id()`
    """
    base = f"{settings.CLOUDINARY_ROOT_FOLDER}/{folder}"
    return f"{base}/u{user_id}" if user_id else base


def owns_public_id(public_id: str, folder: str, user_id: int) -> bool:
    """
    True if this public_id sits in this user's own subfolder.

    Used when creating an item: the client sends back the public_id that the
    upload endpoint gave it, and we confirm they are not pointing at somebody
    else's photo.
    """
    if not public_id:
        return False
    return public_id.startswith(f"{folder_for(folder, user_id)}/")


def upload_image(
    file: IO[bytes] | bytes | str,
    folder: str,
    *,
    user_id: int | None = None,
    public_id: str | None = None,
    tags: list[str] | None = None,
    overwrite: bool = False,
) -> UploadedImage:
    """
    Send one image to Cloudinary and return where it landed.

    Args:
        file:      an open file, raw bytes, or a local path.
        folder:    use a constant from `Folder`, e.g. Folder.GARMENT_CLEAN.
        user_id:   puts the file in that user's own subfolder.
        public_id: optional fixed name. Give one when a file should REPLACE an
                   earlier version (a user's body photo, say). Leave it out and
                   Cloudinary generates a random unique name.
        tags:      helpful for finding or bulk-deleting images later.
        overwrite: only meaningful together with public_id.

    Raises:
        CloudinaryNotConfigured: if the .env keys are missing.
    """
    _require_config()

    full_folder = folder_for(folder, user_id)

    options: dict[str, Any] = {
        "folder": full_folder,
        "resource_type": "image",
        # Strip GPS coordinates and camera details from the user's photo.
        # A wardrobe app should not be publishing where someone lives.
        "image_metadata": False,
        "invalidate": True,  # clear the CDN cache when replacing an image
    }
    if public_id:
        options["public_id"] = public_id
        options["overwrite"] = overwrite
    if tags:
        options["tags"] = tags

    result = cloudinary.uploader.upload(file, **options)

    logger.info(
        "Uploaded image to Cloudinary: %s (%s KB)",
        result["public_id"],
        round(result.get("bytes", 0) / 1024),
    )

    return UploadedImage(
        url=result["secure_url"],
        public_id=result["public_id"],
        width=result.get("width", 0),
        height=result.get("height", 0),
        bytes=result.get("bytes", 0),
        format=result.get("format", ""),
    )


def delete_image(public_id: str) -> bool:
    """
    Permanently remove one image.

    Returns True if it was deleted or was already gone. We never raise here:
    failing to delete an old thumbnail should not break the user's request.
    """
    if not is_configured() or not public_id:
        return False

    try:
        result = cloudinary.uploader.destroy(public_id, invalidate=True)
        return result.get("result") in {"ok", "not found"}
    except Exception:
        logger.exception("Could not delete Cloudinary image %s", public_id)
        return False


def thumbnail_url(url: str, width: int = 400) -> str:
    """
    Turn a full-size image URL into a smaller one, with no re-upload.

    Cloudinary resizes on the fly based on the URL path, so a closet grid of 40
    items downloads 40 small images instead of 40 full-resolution photos. This
    is the single biggest performance win in the whole app.

        .../upload/v123/lumiere/garments/clean/shirt.png
        .../upload/c_limit,w_400,f_auto,q_auto/v123/lumiere/.../shirt.png

    f_auto = best format for the browser (WebP/AVIF), q_auto = smart compression.
    """
    marker = "/upload/"
    if marker not in url:
        return url
    head, tail = url.split(marker, 1)
    return f"{head}{marker}c_limit,w_{width},f_auto,q_auto/{tail}"


def ping() -> dict[str, Any]:
    """
    Check the credentials actually work. Used by our setup test and by the
    health check. Returns Cloudinary's usage summary.
    """
    _require_config()
    return cloudinary.api.ping()
